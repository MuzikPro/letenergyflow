/**
 * Interface translations.
 *
 * WHAT BELONGS HERE: chrome — buttons, headings, navigation, status labels,
 * short instructions. This project wrote those, so this project may translate
 * them.
 *
 * WHAT MUST NEVER BE ADDED HERE: anything read out of a source. The 定位
 * location texts, point and channel names, classical quotations, the
 * curriculum lessons and every 功效／主治 field were taken from cited works in
 * 繁體中文 and rendered into English by the project's own editorial passes.
 * Adding a French or Russian rendering of one of those would be inventing a
 * translation of a medical source — the single thing `AGENTS.md` forbids
 * without exception — and it would arrive wearing the same provenance badge as
 * the reviewed text. `ui.test.ts` fails if a key here looks like curated
 * content rather than chrome.
 *
 * Keyed by the ENGLISH string exactly as it appears in the `t('中文',
 * 'English')` call. A key that is absent falls back to English, which is
 * honest and readable; a wrong key is simply never consulted. There is no
 * partial-translation state that can silently show the wrong language.
 */
