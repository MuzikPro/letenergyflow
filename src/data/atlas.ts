/* --------------------------------------------------------------------------
 * LANDMARK-FIRST PLACEMENT
 *
 * Every point coordinate must be derived from a fixed, unambiguous surface
 * landmark plus a bone-cun (骨度分寸) distance — never estimated by eye. This
 * block defines those landmarks and the per-segment cun scales that GB/T
 * 12346-2021 measures against.
 *
 * WHY PER-SEGMENT SCALES: bone-cun is a proportional system. Each body segment
 * is divided into its own fixed number of units (forearm crease-to-crease = 12,
 * hip-to-popliteal = 19, xiphisternum-to-umbilicus = 8 …), so one cun is a
 * different number of pixels in each segment. Deriving each scale from the two
 * landmarks that bound its own segment means a point lands at its stated
 * distance from its own anchor even where the schematic's proportions differ
 * from a real body — which they do, because the figure is drawn to a 7.5-head
 * artistic canon, not to bone-cun.
 *
 * These are still layout coordinates on a schematic. Landmark anchoring makes
 * them internally consistent and reproducible; it does not make them validated
 * anatomical coordinates, and every placement stays `schematic_unvalidated`.
 * -------------------------------------------------------------------------- */

type Guide = readonly (readonly [number, number])[];

const dist = (a: readonly [number, number], b: readonly [number, number]) =>
  Math.hypot(b[0] - a[0], b[1] - a[1]);

/**
 * A point at `d` pixels along a limb centre-line, offset perpendicular by
 * `off` pixels. Positive `off` is to the RIGHT of the direction of travel
 * (which runs proximal → distal), so callers work in body terms, not pixels.
 */
function alongGuide(g: Guide, d: number, off = 0): { x: number; y: number } {
  let remaining = d;
  for (let i = 0; i < g.length - 1; i++) {
    const a = g[i]!;
    const b = g[i + 1]!;
    const len = dist(a, b);
    const last = i === g.length - 2;
    if (remaining <= len || last) {
      const t = len === 0 ? 0 : remaining / len;
      const ux = (b[0] - a[0]) / (len || 1);
      const uy = (b[1] - a[1]) / (len || 1);
      return {
        x: a[0] + (b[0] - a[0]) * t - uy * off,
        y: a[1] + (b[1] - a[1]) * t + ux * off,
      };
    }
    remaining -= len;
  }
  return { x: g[0]![0], y: g[0]![1] };
}

/**
 * Where the anterior axillary fold crosses the upper-arm guide, as a fraction
 * of the shoulder→elbow span. The guide starts at the shoulder JOINT, but the
 * standard's 9-cun upper arm is measured from the axillary FOLD, which sits
 * lower. Approximated once here so every upper-arm point inherits it.
 */
const AXILLA_FRACTION = 0.26;

function armGeometry(g: Guide) {
  const upper = dist(g[0]!, g[1]!);
  const fore = dist(g[1]!, g[2]!);
  return {
    /** Distance along the guide to each anchor. */
    axilla: upper * AXILLA_FRACTION,
    elbowCrease: upper,
    wristCrease: upper + fore,
    /** 腋前紋頭至肘橫紋 = 9 寸. */
    upperArmCun: (upper * (1 - AXILLA_FRACTION)) / 9,
    /** 肘橫紋至腕橫紋 = 12 寸. */
    forearmCun: fore / 12,
  };
}

function legGeometry(g: Guide) {
  const thigh = dist(g[0]!, g[1]!);
  const shank = dist(g[1]!, g[2]!);
  return {
    hip: 0,
    knee: thigh,
    ankle: thigh + shank,
    /** 股骨大轉子至膕橫紋 = 19 寸. */
    thighCun: thigh / 19,
    /** 膕橫紋至外踝尖 = 16 寸 (lateral / posterior channels). */
    shankLateralCun: shank / 16,
    /** 脛骨內側髁下方至內踝尖 = 13 寸 (medial channels). */
    shankMedialCun: shank / 13,
    /** 臀下橫紋至膕橫紋 = 14 寸 (posterior thigh, 承扶 → 委中). */
    posteriorThighCun: thigh / 14,
  };
}

