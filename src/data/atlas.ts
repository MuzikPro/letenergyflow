/**
 * A point on the leg, measured in cun from a landmark. `cun` is positive
 * DISTAL. `scale` picks the 16-cun lateral/posterior measure or the 13-cun
 * medial one below the knee; above the knee both use the 19-cun thigh.
 */
export function legPoint(
  side: 'left' | 'right',
  from: LegAnchor,
  cun: number,
  lateral = 0,
  scale: 'lateral' | 'medial' = 'lateral',
): { x: number; y: number } {
  const g = side === 'left' ? LIMB_GUIDES.legLeft : LIMB_GUIDES.legRight;
  const geom = LEG_GEOM[side];
  // The patellar borders are levels on the drawn knee; convert them to distance
  // along the guide so a thigh point measured from 髕底 lands correctly.
  const along: Record<LegAnchor, number> = {
    hip: 0,
    // The guide starts level with the crotch, which is where the gluteal fold
    // crosses the back of the thigh.
    glutealFold: 0,
    patellaSuperior: geom.knee - (LEVELS.knee - LANDMARKS.patellaSuperior),
    patellaInferior: geom.knee + (LANDMARKS.patellaInferior - LEVELS.knee),
    poplitealCrease: geom.knee,
    malleolus: geom.ankle,
  };
  // Above the knee the 19-cun thigh; below it the 16-cun lateral/posterior or
  // 13-cun medial measure, whichever the channel is defined against.
  const shankCun = scale === 'medial' ? geom.shankMedialCun : geom.shankLateralCun;
  const px =
    from === 'glutealFold'
      ? geom.posteriorThighCun
      : from === 'hip' || from === 'patellaSuperior' || (from === 'patellaInferior' && cun < 0)
        ? geom.thighCun
        : shankCun;
  const sign = side === 'left' ? -1 : 1;
  return alongGuide(g, along[from] + cun * px, lateral * px * sign);
}

/** A trunk point: a landmark level (or cun from one) plus a lateral cun offset. */
export function trunkPoint(
  side: 'left' | 'right' | 'midline',
  level: number,
  lateralCun = 0,
): { x: number; y: number } {
  const sign = side === 'left' ? 1 : side === 'right' ? -1 : 0;
  return { x: MID + sign * lateralCun * CUN.trunkWidth, y: level };
}

