/**
 * The rectangle the drawn figure actually occupies, per view.
 *
 * Derived by scanning the shapes' own numbers rather than measured in a
 * browser or written down: a detail frame that extends past the figure is
 * showing empty background, and the head frame was spending a quarter of its
 * height on the blank space above the skull.
 *
 * Curve control points are included, so the box can be marginally larger than
 * the true silhouette. That is the safe direction — it never crops anything.
 */
const boundsCache = new Map<BodyViewId, { x: number; y: number; w: number; h: number }>();

export function figureBounds(view: BodyViewId) {
  const hit = boundsCache.get(view);
  if (hit) return hit;

  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  const see = (x: number, y: number) => {
    if (!Number.isFinite(x) || !Number.isFinite(y)) return;
    minX = Math.min(minX, x);
    minY = Math.min(minY, y);
    maxX = Math.max(maxX, x);
    maxY = Math.max(maxY, y);
  };

  for (const s of figureShapes[view]) {
    if (s.kind === 'circle') {
      const { cx = 0, cy = 0, r = 0 } = s;
      see(cx - r, cy - r);
      see(cx + r, cy + r);
      continue;
    }
    // Path data is "C x,y x,y x,y" style throughout this file: every number is
    // a coordinate, alternating x and y.
    const nums = (s.d ?? '').match(/-?\d+(\.\d+)?/g);
    if (!nums) continue;
    for (let i = 0; i + 1 < nums.length; i += 2) {
      see(Number(nums[i]), Number(nums[i + 1]));
    }
  }

  const box = { x: minX, y: minY, w: maxX - minX, h: maxY - minY };
  boundsCache.set(view, box);
  return box;
}

