/* -------------------------------------------------------------------------- *
 * Extremity frames — origin at wrist/ankle, +y distal, +x lateral.
 * -------------------------------------------------------------------------- */

interface Frame {
  ox: number;
  oy: number;
  dx: number;
  dy: number;
  lx: number;
  ly: number;
}

function makeFrame(
  origin: readonly [number, number],
  towards: readonly [number, number],
  lateralSign: 1 | -1,
): Frame {
  const vx = towards[0] - origin[0];
  const vy = towards[1] - origin[1];
  const len = Math.hypot(vx, vy) || 1;
  const dx = vx / len;
  const dy = vy / len;
  return { ox: origin[0], oy: origin[1], dx, dy, lx: -dy * lateralSign, ly: dx * lateralSign };
}

const at = (f: Frame, lx: number, ly: number): [number, number] => [
  f.ox + f.dx * ly + f.lx * lx,
  f.oy + f.dy * ly + f.ly * lx,
];

