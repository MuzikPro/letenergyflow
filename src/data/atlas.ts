/* --------------------------------------------------------------------------
 * EXTREMITY DETAIL VIEWS
 *
 * The hands and feet carry the densest cluster of points on the whole figure —
 * 井穴, 滎穴, 輸穴 and the web-space points all sit within a few millimetres of
 * each other. At whole-body zoom their labels cannot all be drawn, so each
 * extremity gets its own zoomed detail view.
 *
 * The box below is computed from the SAME loop and digit geometry that draws
 * the hand or foot, so the detail view can never disagree with the main model:
 * it is a second camera on one drawing, not a second drawing.
 * -------------------------------------------------------------------------- */

export interface ExtremityRegion {
  id: 'hand-left' | 'hand-right' | 'foot-left' | 'foot-right';
  kind: 'hand' | 'foot';
  side: 'left' | 'right';
  labelZhHant: string;
  labelEn: string;
  /** Bounding box in atlas user units, padded for context. */
  box: { x: number; y: number; w: number; h: number };
  /** Centre of the hotspot the learner taps on the whole-body figure. */
  hotspot: { x: number; y: number; r: number };
}

function extremityBox(frame: Frame, kind: 'hand' | 'foot') {
  /*
   * The UNION of both views' geometry, not the front's alone.
   *
   * The posterior foot reaches further down its lateral border than the dorsal
   * one does, and this box drives the detail camera and the hotspot. Sizing it
   * from one view would crop the other — and cropping is the failure this box
   * was written to avoid.
   */
  const loop =
    kind === 'hand' ? PALM_LOOP : ([...FOOT_LOOP, ...POSTERIOR_FOOT_LOOP] as [number, number][]);
  const digits = kind === 'hand' ? DIGITS : [...TOES, ...POSTERIOR_TOES];
  const locals: [number, number][] = [
    ...loop,
    ...digits.flatMap((d) =>
      d.pts.map((pt, i): [number, number] => [pt[0], pt[1] + (d.w[i] ?? 0)]),
    ),
    ...digits.flatMap((d) => d.pts.map((pt, i): [number, number] => [pt[0] + (d.w[i] ?? 0), pt[1]])),
    ...digits.flatMap((d) => d.pts.map((pt, i): [number, number] => [pt[0] - (d.w[i] ?? 0), pt[1]])),
  ];
  const pts = locals.map(([lx, ly]) => at(frame, lx, ly));
  const xs = pts.map((q) => q[0]);
  const ys = pts.map((q) => q[1]);
  // Padding for the shape, plus a wider allowance on +x where the detail view
  // draws its labels — without it the outermost 井穴 label (少商, 至陰) is
  // clipped by the viewBox edge.
  const pad = 10;
  const labelRoom = 30;
  const x = Math.min(...xs) - pad;
  const y = Math.min(...ys) - pad;
  return {
    box: { x, y, w: Math.max(...xs) - x + pad + labelRoom, h: Math.max(...ys) - y + pad },
    centre: at(frame, 0, kind === 'hand' ? 30 : 24),
  };
}

const extremity = (
  id: ExtremityRegion['id'],
  kind: 'hand' | 'foot',
  side: 'left' | 'right',
  labelZhHant: string,
  labelEn: string,
): ExtremityRegion => {
  const frame = kind === 'hand' ? handFrames[side] : footFrames[side];
  const { box, centre } = extremityBox(frame, kind);
  return {
    id,
    kind,
    side,
    labelZhHant,
    labelEn,
    box,
    hotspot: { x: centre[0], y: centre[1], r: kind === 'hand' ? 30 : 24 },
  };
};

