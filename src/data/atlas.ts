/**
 * Build a smooth, tapered limb silhouette around a centre-line.
 *
 * The outline is generated by offsetting each centre-line vertex along its
 * normal by a per-vertex half-width, adding rounded end caps, and running the
 * whole ring through the Catmull-Rom smoother. Because the input IS the limb
 * guide the markers anchor to, the drawing can never drift away from the data.
 */
export function limbOutline(
  pts: readonly (readonly [number, number])[],
  halfWidths: readonly number[],
): string {
  if (pts.length < 2 || pts.length !== halfWidths.length) return '';
  const dirs = pts.map((_, i) => {
    const a = pts[Math.max(0, i - 1)]!;
    const b = pts[Math.min(pts.length - 1, i + 1)]!;
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const len = Math.hypot(dx, dy) || 1;
    return { x: dx / len, y: dy / len };
  });
  const left = pts.map((p, i) => ({
    x: p[0] - dirs[i]!.y * halfWidths[i]!,
    y: p[1] + dirs[i]!.x * halfWidths[i]!,
  }));
  const right = pts.map((p, i) => ({
    x: p[0] + dirs[i]!.y * halfWidths[i]!,
    y: p[1] - dirs[i]!.x * halfWidths[i]!,
  }));
  const first = pts[0]!;
  const last = pts[pts.length - 1]!;
  const startCap = {
    x: first[0] - dirs[0]!.x * halfWidths[0]! * 0.9,
    y: first[1] - dirs[0]!.y * halfWidths[0]! * 0.9,
  };
  const endCap = {
    x: last[0] + dirs[dirs.length - 1]!.x * halfWidths[halfWidths.length - 1]! * 0.9,
    y: last[1] + dirs[dirs.length - 1]!.y * halfWidths[halfWidths.length - 1]! * 0.9,
  };
  return `${smoothPath([startCap, ...left, endCap, ...[...right].reverse()])} Z`;
}

