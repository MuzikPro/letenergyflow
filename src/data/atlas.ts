export type ArmAnchor = 'axilla' | 'elbowCrease' | 'wristCrease';

/**
 * A point on the arm, measured in cun from a crease.
 *
 * `cun` is signed along the limb: positive is DISTAL (toward the hand),
 * negative PROXIMAL. It is scaled by the segment the measurement belongs to —
 * upper arm above the elbow crease, forearm below it. `lateral` is in the same
 * segment's cun, positive AWAY from the body midline.
 */
export function armPoint(
  side: 'left' | 'right',
  from: ArmAnchor,
  cun: number,
  lateral = 0,
): { x: number; y: number } {
  const g = side === 'left' ? LIMB_GUIDES.armLeft : LIMB_GUIDES.armRight;
  const geom = ARM_GEOM[side];
  // The scale is the segment the measurement lies in: above the elbow crease
  // the 9-cun upper arm, below it the 12-cun forearm.
  const px =
    from === 'axilla' || (from === 'elbowCrease' && cun < 0)
      ? geom.upperArmCun
      : geom.forearmCun;
  // `alongGuide` offsets to the right of the proximal→distal direction, which
  // is toward -x on both limbs. Flip per side so `lateral` always means AWAY
  // from the body midline.
  const sign = side === 'left' ? -1 : 1;
  return alongGuide(g, geom[from] + cun * px, lateral * px * sign);
}

