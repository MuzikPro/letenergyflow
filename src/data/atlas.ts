/** Fractional position along a limb guide, offset laterally in px. */
export function alongLimb(
  guide: readonly (readonly [number, number])[],
  t: number,
  lateral = 0,
): { x: number; y: number } {
  const segs: number[] = [];
  let total = 0;
  for (let i = 0; i < guide.length - 1; i++) {
    const L = Math.hypot(guide[i + 1]![0] - guide[i]![0], guide[i + 1]![1] - guide[i]![1]);
    segs.push(L);
    total += L;
  }
  let want = Math.max(0, Math.min(1, t)) * total;
  for (let i = 0; i < segs.length; i++) {
    if (want <= segs[i]! || i === segs.length - 1) {
      const f = segs[i] ? want / segs[i]! : 0;
      const a = guide[i]!;
      const b = guide[i + 1]!;
      const dx = (b[0] - a[0]) / (segs[i] || 1);
      const dy = (b[1] - a[1]) / (segs[i] || 1);
      return { x: a[0] + (b[0] - a[0]) * f - dy * lateral, y: a[1] + (b[1] - a[1]) * f + dx * lateral };
    }
    want -= segs[i]!;
  }
  const last = guide[guide.length - 1]!;
  return { x: last[0], y: last[1] };
}

