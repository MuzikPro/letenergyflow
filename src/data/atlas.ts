/**
 * Back-view vertebral ladder.
 *
 * The back-shu points are located BY vertebral level ("below the spinous
 * process of T3, 1.5 cun lateral"), so the figure needs that ladder as real
 * coordinates rather than eyeballed dots.
 *
 * The whole ladder is one measurement now, hung between the two features of
 * this figure that a spine actually has to fit between: the drawn C7 at the
 * neck base, and the drawn coccyx tip. Both come from the HRA reference spine
 * (CC BY 4.0 — cited on the About page, and surveyed in
 * content-review/3d-asset-survey-2026-08-22.md).
 *
 * WHY NOT A CHOSEN STEP: the ladder used to step 13.6 px through the thoracic
 * spine and 14 px through the lumbar — a ratio of 1.029, where the reference
 * spine gives 1.225, and a thoracic step so coarse that all 23.6 levels needed
 * 321 px of trunk when only 290 px exist. It could not close, so the sacrum
 * absorbed the difference and 八髎 sat about 12% too tight.
 *
 * The drawn figure was NOT the problem and has not been touched: C7 to coccyx
 * tip is 34.83% of this figure's height against the model's 34.53%, right to
 * 0.30%. Only the step inside that span was wrong.
 *
 * WHAT THE NAVEL COSTS: L2 no longer lands exactly on it. The owner's worksheet
 * states 「與臍相平」 for 命門 GV4 and this ladder puts the navel about half a
 * lumbar interval below L2 — closer to L2/L3, where modern anatomy generally
 * puts it too. Owner's decision, 2026-08-22: the anatomical ladder wins and the
 * teaching text is reviewed separately.
 */
const LADDER_TOP = LEVELS.neckBase + 9;
const COCCYX_Y = 476;

/*
 * The reference spine, as metres below its own C7 spinous process. The two
 * steps are least-squares fits through its spinous tips; the C7→T1 and
 * C7→coccyx offsets are measured directly. Uniform steps rather than the
 * model's per-level gaps — the fit's residual is 0.13 of a level, so the
 * individual gaps are one body's noise and copying them would be overfitting.
 */
const M_C7_T1 = 0.0205;
const M_T_STEP = 0.02676;
const M_L_STEP = 0.0328;
const M_C7_COCCYX = 0.6317;

/** One scale, so the ladder closes on the drawn coccyx tip by construction. */
const PX_PER_M = (COCCYX_Y - LADDER_TOP) / M_C7_COCCYX;
const T_STEP = M_T_STEP * PX_PER_M;
const L_STEP = M_L_STEP * PX_PER_M;
const T1_Y = LADDER_TOP + M_C7_T1 * PX_PER_M;
const T12_Y = T1_Y + 11 * T_STEP;
const L5_Y = T12_Y + 5 * L_STEP;
/**
 * The sacrum is the one segment that cannot be measured — the reference model
 * carries it as a single fused mesh with no posterior foramina — so the block
 * keeps the shape it had and is fitted into whatever span the ladder leaves.
 * It used to span 66 px from L5 to the coccyx; it now gets 70.
 */
const SACRAL_FIT = (COCCYX_Y - L5_Y) / 66;

export const SPINE = {
  /** T1..T12 spinous processes. */
  t: (n: number) => T1_Y + (n - 1) * T_STEP,
  /** L1..L5. */
  l: (n: number) => T12_Y + n * L_STEP,
  /** S1..S4 posterior sacral foramina. */
  s: (n: number) => L5_Y + (14 + (n - 1) * 12) * SACRAL_FIT,
  coccyx: COCCYX_Y,
} as const;

